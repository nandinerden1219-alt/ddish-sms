Konka бол ДДэш-ийн анхны үеийн төхөөрөмж.

Дохио шалгах:
- Удирдлагын 4 өнгийн товчлуураас ЦЭНХЭР товчийг дарахад "Антен тохируулах" цонх гарна (бусад төхөөрөмжөөс ялгаатай нь ийм нэртэй гарна).
- Цэснээс орж ч болно: SW нь 7-оор эхэлсэн бол Цэс → Антен → Антен тохируулах. SW нь 1-ээр эхэлсэн бол Цэс → Тохиргоо → Антен тохируулах.
- Доор нь I ба Q гэсэн 2 тоо байна: I = дохионы хүч, Q = дохионы чанар.
- I хамгийн багадаа 11 заана (11 бол дохио бараг алга гэсэн үг). Q хамгийн багадаа 0 заана.

Тоогоор дүгнэх (Konka-гийн босго):
- I 80%-иас доош: кабель утас, дуран (LNB), оролтуудаа шалгана.
- I 80%-иас дээш болж байж Q (чанар) орж ирнэ.
- I 80%-иас дээш боловч Q 45-аас бага эсвэл 0: антен тааралгүй байна, "Антен тааруулах" зааврын дагуу тааруулж Q-г 45-аас дээш болгоно.
- Антенаа тааруулсан ч Q 0 хэвээр, огт орж ирэхгүй бол: код болон хүлээн авагчийн хувилбарыг (SW) шалгана.

Хүлээн авагчийн хувилбар (SW) шалгах:
- Удирдлагын 4 өнгийн товчлуураас УЛААН товчийг дарахад "Operator ID 976" гарна, OK дарахад Software version (хүлээн авагчийн хувилбар) гарна.
- Цэснээс харах: SW 7.00.05 дээр Цэс → Бусад → Системийн мэдээлэл. SW 1.11.21 дээр Цэс → Нэмэлт мэдээлэл → Системийн мэдээлэл.

Reset (анхны төлөвт оруулах):
Reset гэдэг нь хүлээн авагчийг анхны горимд оруулах тохиргоо. Konka дээр reset хийхэд төхөөрөмжийн кодууд анхны код руугаа буцдаг.
- SW 7.00.05 эсвэл SW 1.11.21 байвал шууд reset хийлгэж болно. Reset хийсний дараа кодууд хэвийн болно.
- Өөр SW-тэй үед reset хийсэн бол заавал код шивж байж таарна (доорх код шивэх заавар).

SW 7.00.05 дээр цэсэнд "Анхны төлөвт оруулах" гэж гарна:
Цэс → Суваг → Анхны төлөв сэргээх → Нууц үг 0000 → "Сэргээж дууслаа" → Гарах

SW 1.11.21 дээр цэсэнд "Ресет хийх" гэж гарна:
Цэс → Суваг → Ресет хийх → Нууц үг 0000 → "Амжилттай хийгдлээ" → Гарах

